#!/usr/bin/env python3
"""Writes the reference pages in docs/reference/ from the source, so they can't drift:

    cli.md          every command's --help (the built CLI)
    expressions.md  the expression functions (crates/expr/src/functions.rs), with their argument counts
    settings.md     every settings key with its type, default and note (app/ui/src/settings.svelte.ts)
    shortcuts.md    the menu bar's commands and their shortcuts (app/ui/src/commands.ts)

    python3 tools/reference.py [--bin PATH]           write the pages
    python3 tools/reference.py --check [--bin PATH]   compare instead, and exit 1 when a page is stale (`just lint`)

The CLI page needs the CLI built: --bin, else $TLMBENCH_BIN, else target/release/tlmbench, else target/debug/tlmbench.
--check also fails when an expression function is missing from the manual's function reference (chapter 5).
"""

from __future__ import annotations

import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "reference"
HEAD = "Generated by `tools/reference.py` (`just reference`). Do not edit; `just lint` fails when this page is out of date."


def read(path: str) -> str:
    return (ROOT / path).read_text(encoding="utf-8")


# ---- CLI -------------------------------------------------------------------------------------------------------------


def find_bin(arg: str | None) -> Path:
    for c in [arg, os.environ.get("TLMBENCH_BIN"), ROOT / "target/release/tlmbench", ROOT / "target/debug/tlmbench"]:
        for p in (Path(c), Path(f"{c}.exe")) if c else ():
            if p.is_file():
                return p
    sys.exit("reference.py: the CLI isn't built (cargo build --bin tlmbench, or pass --bin)")


def help_of(exe: Path, *args: str) -> str:
    out = subprocess.run([str(exe), *args, "--help"], capture_output=True, text=True, encoding="utf-8", check=True).stdout
    # the same page on every OS: clap prints the program's file name, `tlmbench.exe` on Windows
    return out.replace("tlmbench.exe", "tlmbench").rstrip() + "\n"


def commands(top: str) -> list[str]:
    names, on = [], False
    for line in top.splitlines():
        if line.startswith("Commands:"):
            on = True
        elif on and line.startswith("  ") and not line.startswith("   "):
            names.append(line.split()[0])
        elif on and not line.strip():
            break
    return [n for n in names if n != "help"]


def cli(exe: Path) -> str:
    top = help_of(exe)
    lines = ["# Command line reference", "", HEAD, "", "The output of `tlmbench --help` and of each command's `--help`.", "", "## tlmbench", "", "```", top.rstrip(), "```"]

    def walk(path: list[str]) -> None:
        text = help_of(exe, *path)
        lines.extend(["", "#" * (len(path) + 2) + f" tlmbench {' '.join(path)}", "", "```", text.rstrip(), "```"])
        for s in commands(text):
            walk([*path, s])

    for s in commands(top):
        walk([s])
    return "\n".join(lines) + "\n"


# ---- expressions -----------------------------------------------------------------------------------------------------


def expressions() -> str:
    src = read("crates/expr/src/functions.rs")
    table = src[src.index("pub const TABLE") : src.index("];")]
    groups: list[tuple[str, list[tuple[str, int, int]]]] = []
    for line in table.splitlines():
        m = re.match(r"\s*//\s*(.+)", line)
        if m and not line.strip().startswith("pub"):
            groups.append((m.group(1).strip(), []))
            continue
        m = re.match(r'\s*\("(\w+)",\s*(\d+),\s*(\d+)\)', line)
        if m:
            if not groups:
                groups.append(("functions", []))
            groups[-1][1].append((m.group(1), int(m.group(2)), int(m.group(3))))
    lines = ["# Expression functions", "", HEAD, "", "Every function a check, rule or derived channel can call, from the table in `crates/expr/src/functions.rs`.", "The manual's [function reference](../manual/05-channels.md) says what each one does.", ""]
    for title, fns in groups:
        lines += [f"## {title[0].upper() + title[1:]}", "", "| Function | Arguments |", "| --- | --- |"]
        for n, lo, hi in fns:
            lines.append(f"| `{n}` | {lo if lo == hi else f'{lo} to {hi}'} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def expression_names() -> list[str]:
    return re.findall(r'^\s*\("(\w+)",\s*\d+,\s*\d+\)', read("crates/expr/src/functions.rs"), re.M)


def manual_gaps() -> list[str]:
    text = read("docs/manual/05-channels.md")
    return [n for n in expression_names() if not re.search(rf"`{re.escape(n)}\b", text)]


# ---- settings --------------------------------------------------------------------------------------------------------


def settings() -> str:
    src = read("app/ui/src/settings.svelte.ts")
    body = src[src.index("export interface Settings") :]
    body = body[: body.index("\n}\n")]
    defaults = src[src.index("export const DEFAULTS: Settings = {") :]
    defaults = defaults[: defaults.index("\n};")]
    dflt: dict[str, str] = {}
    for line in defaults.splitlines()[1:]:
        m = re.match(r"\s{2}(\w+):\s*(.+?),?\s*$", line)
        if m:
            dflt[m.group(1)] = m.group(2)
    rows, note = [], ""
    for line in body.splitlines()[1:]:
        s = line.strip()
        m = re.match(r"/\*\*\s*(.*?)\s*\*/$", s)
        if m:
            note = (note + " " + m.group(1)).strip()
            continue
        m = re.match(r"(\w+)\??:\s*(.+?);", s)
        if m:
            rows.append((m.group(1), m.group(2), dflt.get(m.group(1), ""), note))
            note = ""
        elif s and not s.startswith("//"):
            note = ""
    lines = [
        "# Settings keys",
        "",
        HEAD,
        "",
        "Every key the app saves, from `app/ui/src/settings.svelte.ts` (the `Settings` type and `DEFAULTS`). The labels in Settings are in the manual's [Settings chapter](../manual/14-settings.md); a note here is the source's own comment, and is shared by the keys it sits over.",
        "",
        "| Key | Type | Default | Note |",
        "| --- | --- | --- | --- |",
    ]
    esc = lambda t: t.replace("|", "\\|")  # noqa: E731
    for k, t, d, n in rows:
        lines.append(f"| `{k}` | `{esc(t)}` | `{esc(d)}` | {esc(n)} |")
    return "\n".join(lines) + "\n"


# ---- shortcuts -------------------------------------------------------------------------------------------------------


def shortcut(accel: str | None, key: str | None) -> str:
    if key:
        return key
    if not accel:
        return ""
    mac = accel.replace("CmdOrCtrl", "⌘").replace("Shift", "⇧").replace("Alt", "⌥").replace("+", "")
    win = accel.replace("CmdOrCtrl", "Ctrl")
    return f"{mac} / {win}"


def shortcuts() -> str:
    src = read("app/ui/src/commands.ts")
    table = src[src.index("export const COMMANDS") :]
    table = table[: table.index("\n];")]
    menus: dict[str, list[tuple[str, str]]] = {}
    for line in table.splitlines():
        m = re.search(r"\{\s*id:\s*'(\w+)',\s*menu:\s*'(\w+)',\s*label:\s*'([^']*)'(.*)\}", line)
        if not m:
            continue
        rest = m.group(4)
        a = re.search(r"accel:\s*'([^']*)'", rest)
        k = re.search(r"key:\s*'([^']*)'", rest)
        menus.setdefault(m.group(2), []).append((m.group(3), shortcut(a and a.group(1), k and k.group(1))))
    lines = [
        "# Menu bar commands and shortcuts",
        "",
        HEAD,
        "",
        "The desktop app's menu bar, from the command table in `app/ui/src/commands.ts`. A combination is shown for macOS, then for Windows and Linux; a single key (F, E, Esc) works with the window focused and is never bound by the menu. The manual's [Keyboard and mouse chapter](../manual/15-keyboard-and-mouse.md) adds the keys that are not menu items.",
        "",
    ]
    for menu, items in menus.items():
        lines += [f"## {menu}", "", "| Command | Shortcut |", "| --- | --- |"]
        lines += [f"| {label} | {sc or '—'} |" for label, sc in items]
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


# ---- main ------------------------------------------------------------------------------------------------------------


def main() -> int:
    args = sys.argv[1:]
    check = "--check" in args
    exe = find_bin(args[args.index("--bin") + 1] if "--bin" in args else None)
    pages = {"cli.md": cli(exe), "expressions.md": expressions(), "settings.md": settings(), "shortcuts.md": shortcuts()}
    bad = []
    if check:
        gaps = manual_gaps()
        if gaps:
            print("reference: functions missing from the manual's function reference (docs/manual/05-channels.md): " + ", ".join(gaps))
            bad.append("manual")
        for name, text in pages.items():
            f = OUT / name
            if not f.exists() or f.read_text(encoding="utf-8") != text:
                print(f"reference: docs/reference/{name} is out of date: run `just reference`")
                import difflib

                old = f.read_text(encoding="utf-8").splitlines() if f.exists() else []
                print("\n".join(list(difflib.unified_diff(old, text.splitlines(), "committed", "generated", lineterm=""))[:40]))
                bad.append(name)
        return 1 if bad else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in pages.items():
        (OUT / name).write_text(text, encoding="utf-8", newline="\n")
        print(f"docs/reference/{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
